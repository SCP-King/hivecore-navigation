"""G4.3 PCD/Bag evidence comparison and RESEARCH-ONLY A* reference.

Consumes previously exported G4.0 PCD slice and G4.2 Bag-ray PGM/JSON.
No ROS, no publishers, no robot motion. Ray-visible is NOT traversable.
"""
from collections import Counter, deque
from heapq import heappop, heappush
from pathlib import Path
import json
import math
import re

UNKNOWN, FREE, OCC = -1, 0, 100


def read_export(prefix):
    p = Path(prefix)
    report = json.loads(p.with_suffix(".json").read_text(encoding="utf-8"))
    raw = p.with_suffix(".pgm").read_bytes()
    header = re.match(rb"^P5\s+([0-9]+)\s+([0-9]+)\s+255\s", raw)
    if header is None:
        raise ValueError("expected binary PGM P5 generated by G4")
    w, h = map(int, header.groups())
    if (w <= 0 or h <= 0 or w * h > 2000000 or
            [w, h] != [report.get("width"), report.get("height")]):
        raise ValueError("PGM/JSON geometry mismatch")
    data = raw[header.end():]
    if len(data) != w * h or set(data) - {0, 205, 254}:
        raise ValueError("invalid G4 PGM categories or pixel count")
    if (not isinstance(report.get("origin"), list) or
            len(report["origin"]) != 2 or
            not all(isinstance(n, (int, float)) and math.isfinite(n)
                    for n in report["origin"])):
        raise ValueError("invalid map origin")
    res = report.get("resolution")
    if not isinstance(res, (int, float)) or not math.isfinite(res) or not .05 <= res <= 1.:
        raise ValueError("invalid map resolution")
    # PGM top-left raster -> ROS lower-left grid.
    m = {0: OCC, 205: UNKNOWN, 254: FREE}
    grid = [m[data[(h - 1 - y) * w + x]] for y in range(h) for x in range(w)]
    totals = Counter(grid)
    for value, key in ((OCC, "inflated_occupied_cells"),
                       (UNKNOWN, "unknown_cells"), (FREE, "free_cells")):
        if totals[value] != report.get(key):
            raise ValueError("G4 PGM/JSON category count mismatch")
    return {"grid": grid, "width": w, "height": h,
            "resolution": float(res), "origin": report["origin"],
            "report": report}


def components(grid, w, h):
    visited = bytearray(w * h)
    groups = []
    for root, value in enumerate(grid):
        if value != FREE or visited[root]:
            continue
        queue = deque([root])
        visited[root] = 1
        cells = []
        while queue:
            i = queue.popleft()
            cells.append(i)
            x, y = i % w, i // w
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                xx, yy = x + dx, y + dy
                if 0 <= xx < w and 0 <= yy < h:
                    j = yy * w + xx
                    if grid[j] == FREE and not visited[j]:
                        visited[j] = 1
                        queue.append(j)
        groups.append(cells)
    return sorted(groups, key=len, reverse=True)


def farthest_cell(start, region, w, h):
    eligible = set(region)
    visited = {start}
    queue = deque([start])
    last = start
    while queue:
        last = queue.popleft()
        x, y = last % w, last // w
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            xx, yy = x + dx, y + dy
            if 0 <= xx < w and 0 <= yy < h:
                j = yy * w + xx
                if j in eligible and j not in visited:
                    visited.add(j)
                    queue.append(j)
    return last


def map_cell(m, xy):
    if len(xy) != 2 or not all(math.isfinite(v) for v in xy):
        raise ValueError("invalid XY")
    x = math.floor((xy[0] - m["origin"][0]) / m["resolution"])
    y = math.floor((xy[1] - m["origin"][1]) / m["resolution"])
    if not (0 <= x < m["width"] and 0 <= y < m["height"]):
        raise ValueError("XY outside map extent")
    return y * m["width"] + x


def astar(m, start, goal):
    g = m["grid"]
    w, h = m["width"], m["height"]
    if g[start] != FREE or g[goal] != FREE:
        raise ValueError("A/B not in observed, nonconflicting ray-free cells")
    gx, gy = goal % w, goal // w
    def heuristic(i):
        dx = abs(i % w - gx)
        dy = abs(i // w - gy)
        return max(dx, dy) + (math.sqrt(2) - 1) * min(dx, dy)
    heap = [(heuristic(start), 0., start)]
    cost = {start: 0.}
    prev = {}
    while heap:
        _, spent, i = heappop(heap)
        if spent > cost.get(i, math.inf) + 1e-9:
            continue
        if i == goal:
            path = [goal]
            while path[-1] != start:
                path.append(prev[path[-1]])
            path.reverse()
            return path, round(spent * m["resolution"], 3)
        x, y = i % w, i // w
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                if not dx and not dy:
                    continue
                xx, yy = x + dx, y + dy
                if not (0 <= xx < w and 0 <= yy < h):
                    continue
                j = yy * w + xx
                if g[j] != FREE:
                    continue
                if dx and dy and (g[y * w + xx] != FREE or g[yy * w + x] != FREE):
                    continue
                candidate = spent + math.hypot(dx, dy)
                if candidate + 1e-9 < cost.get(j, math.inf):
                    cost[j] = candidate
                    prev[j] = i
                    heappush(heap, (candidate + heuristic(j), candidate, j))
    raise ValueError("no route within observed nonconflicting free area")


def audit(ray_prefix, pcd_prefix, *, research_route=False,
          start_xy=None, goal_xy=None):
    ray, pcd = read_export(ray_prefix), read_export(pcd_prefix)
    if (ray["report"].get("schema") != "n01.offline.bag_ray_visibility.v1" or
            pcd["report"].get("schema") != "n01.offline.pcd_goal_preview.v1"):
        raise ValueError("wrong G4.2/G4.0 report schemas")
    if ((ray["width"], ray["height"]) != (pcd["width"], pcd["height"]) or
            abs(ray["resolution"] - pcd["resolution"]) > 1e-9 or
            any(abs(x - y) > 1e-6 for x, y in zip(ray["origin"], pcd["origin"]))):
        raise ValueError("grids do not share an identical map XY lattice")
    pairs = Counter(zip(ray["grid"], pcd["grid"]))
    # PCD-slice obstacles are not verified; disagreement is UNKNOWN.
    filtered = [UNKNOWN if r == FREE and p == OCC else r
                for r, p in zip(ray["grid"], pcd["grid"])]
    m = {"grid": filtered, "width": ray["width"], "height": ray["height"],
         "resolution": ray["resolution"], "origin": ray["origin"]}
    groups = components(filtered, m["width"], m["height"])
    conflicts = [i for i, (r, p) in enumerate(zip(ray["grid"], pcd["grid"]))
                 if r == FREE and p == OCC]
    report = {
        "schema": "n01.offline.pcd_bag_evidence_audit.v1",
        "status": "CONFLICT_AWARE_RAY_VISIBILITY_ONLY_NOT_TRAVERSABILITY",
        "ray_free_cells": ray["report"]["free_cells"],
        "pcd_slice_free_cells": pcd["report"]["free_cells"],
        "ray_free_pcd_slice_obstacle_conflicts": pairs[(FREE, OCC)],
        "ray_hit_pcd_slice_free_conflicts": pairs[(OCC, FREE)],
        "ray_free_pcd_slice_free_agreements": pairs[(FREE, FREE)],
        "ray_free_pcd_slice_unknown": pairs[(FREE, UNKNOWN)],
        "ray_hit_pcd_slice_obstacle_agreements": pairs[(OCC, OCC)],
        "ray_hit_pcd_slice_unknown": pairs[(OCC, UNKNOWN)],
        "free_after_conflict_veto": filtered.count(FREE),
        "occupied_after_conflict_veto": filtered.count(OCC),
        "unknown_after_conflict_veto": filtered.count(UNKNOWN),
        "free_component_count_4_connected": len(groups),
        "largest_free_component_cells": len(groups[0]) if groups else 0,
        "top_free_component_sizes": [len(c) for c in groups[:10]],
        "origin_xy_m": m["origin"], "resolution_m": m["resolution"],
        "dimensions_cells": [m["width"], m["height"]],
        "source_ray_prefix": str(ray_prefix),
        "source_pcd_prefix": str(pcd_prefix),
        "floor_validated": False,
        "robot_full_height_clearance_validated": False,
        "global_reference_algorithm": "NONE",
        "scan_native_planner_connected": False,
        "actuator_output": "DISABLED", "safety_authorization": "NEVER"
    }
    path = []
    if start_xy is not None or goal_xy is not None:
        if start_xy is None or goal_xy is None:
            raise ValueError("start/goal must be provided together")
        research_route = True
    if research_route:
        if not groups or len(groups[0]) < 10:
            report["route_error"] = "insufficient connected observed free space"
        else:
            if start_xy is None:
                a = farthest_cell(groups[0][0], groups[0], m["width"], m["height"])
                b = farthest_cell(a, groups[0], m["width"], m["height"])
                report["selection"] = "AUTO_RESEARCH_ENDPTS_NOT_USER_GOALS"
            else:
                # User coordinates can be outside the limited recorded map.
                # Return a traceable research failure instead of an uncaught
                # exception which would discard the generated conflict report.
                try:
                    a = map_cell(m, start_xy)
                    b = map_cell(m, goal_xy)
                except ValueError as exc:
                    report["route_error"] = str(exc)
                    return report, m, path, conflicts
                report["selection"] = "USER_SELECTED_RESEARCH_ENDPTS"
            try:
                path, distance = astar(m, a, b)
                def center(i):
                    return [round(m["origin"][0] + (i % m["width"] + .5) * m["resolution"], 5),
                            round(m["origin"][1] + (i // m["width"] + .5) * m["resolution"], 5)]
                report["research_start_xy_m"] = center(a)
                report["research_goal_xy_m"] = center(b)
                report["research_path_xy_m"] = [center(i) for i in path]
                report["research_path_length_m"] = distance
                report["global_reference_algorithm"] = "A_STAR_ON_RAY_VISIBILITY_WITH_PCD_CONFLICT_VETO_NOT_SCAN"
                report["route_warning"] = "LIDAR-HEIGHT VISIBILITY ONLY: NOT GROUND OR HIVE2 COLLISION VALIDATION"
            except ValueError as exc:
                report["route_error"] = str(exc)
    return report, m, path, conflicts


def write_outputs(out_prefix, report, m, path, conflicts):
    base = Path(out_prefix)
    base.parent.mkdir(parents=True, exist_ok=True)
    for suffix in (".json", ".svg"):
        if base.with_suffix(suffix).exists():
            raise FileExistsError("refuse overwrite: " + str(base.with_suffix(suffix)))
    w, h = m["width"], m["height"]
    svg = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="1000">',
           f'<rect width="{w}" height="{h}" fill="#939aa1"/>']
    for i, state in enumerate(m["grid"]):
        if state == UNKNOWN:
            continue
        color = "#20242c" if state == OCC else "#ecf7f1"
        svg.append(f'<rect x="{i%w}" y="{h-1-i//w}" width="1" height="1" fill="{color}"/>')
    for i in conflicts:
        svg.append(f'<rect x="{i%w}" y="{h-1-i//w}" width="1" height="1" fill="#d65db1"/>')
    if path:
        coords = " ".join(f"{i%w+.5:.2f},{h-i//w-.5:.2f}" for i in path)
        svg.append(f'<polyline points="{coords}" fill="none" stroke="#00c8ff" stroke-width="1.4"/>')
        for i, color in ((path[0], "#27bc5d"), (path[-1], "#ff4439")):
            svg.append(f'<circle cx="{i%w+.5}" cy="{h-i//w-.5}" r="2" fill="{color}"/>')
    svg.append("</svg>")
    base.with_suffix(".svg").write_text("\n".join(svg), encoding="utf-8")
    base.with_suffix(".json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
